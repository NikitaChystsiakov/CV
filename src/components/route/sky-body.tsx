/**
 * Светило в углу неба: солнце в светлой теме, луна в тёмной.
 *
 * Здесь только свечение, без диска. Нарисованный кодом круг (оранжевый диск с
 * глоу, серый диск с «кратерами») стоял рядом с ассетами владельца и читался
 * как иконка из другой графики — два визуальных языка в одном кадре. Мягкий
 * свет в углу неба таких претензий не вызывает: он не спорит с домами, а
 * освещает их. Диск солнца и луны в технике домов — желаемый ассет владельца
 * (docs/нужны-ассеты.md); когда придёт, он встанет в центр этого же свечения.
 *
 * Слой закреплён и на курсор не реагирует — владелец просил, чтобы фон не ездил
 * за мышью. Созвездия живут отдельно и едут вместе с маршрутом
 * (см. constellations.tsx).
 *
 * Углы поделены: справа закреплена карта маршрута, и её подписи остановок
 * (они торчат влево от звезды) ложились прямо на светило. Поэтому от md
 * светило уходит в левый угол.
 *
 * Посадка по ширинам:
 * - до md светила нет: колонка текста там во всю ширину, и закреплённый свет
 *   на любом скролле оказывался за буквами (`right-[6%] top-[9%]` садился под
 *   текст остановок), а на первом экране его целиком закрывала арка;
 * - md–lg — левый верхний угол, `left-[3%] top-[4%]`, свечение меньше: на
 *   1024 в прежней позиции (`left-[7%] top-[9%]`) и прежнем размере оно сидело
 *   под заголовком первого экрана;
 * - от xl колонка контента уже, и светило опускается в прежний угол.
 *
 * z-10 — выше земли и декора: декор раскладывается по всей длине маршрута и на
 * любом скролле проезжает через закреплённый угол, так что лавочка закрывала
 * луну. Текст остановки поднят в z-20 и остаётся поверх (route-stop.tsx).
 *
 * Переключение между солнцем и луной — на классах `dark:`, без JS: тогда при
 * загрузке не мигает не та картинка.
 */
export function SkyBody() {
  return (
    <div
      aria-hidden
      data-sky-body
      className="pointer-events-none fixed left-[3%] top-[4%] z-10 hidden md:block xl:left-[7%] xl:top-[9%]"
    >
      {/* Солнце: тёплый свет, ядро плотнее, край растворяется в небе */}
      <div
        className="size-48 rounded-full xl:size-72 dark:hidden"
        style={{
          background:
            "radial-gradient(closest-side, color-mix(in oklab, var(--color-accent-2) 46%, transparent) 0%, color-mix(in oklab, var(--color-accent-2) 20%, transparent) 40%, transparent 100%)",
        }}
      />

      {/* Луна: тот же угол, свет холоднее и слабее — на тёмном небе плотное
          пятно читалось бы как прожектор, а не как лунный свет */}
      <div
        className="hidden size-48 rounded-full xl:size-64 dark:block"
        style={
          {
            background:
              "radial-gradient(closest-side, color-mix(in oklab, var(--moonlight) 30%, transparent) 0%, color-mix(in oklab, var(--moonlight) 12%, transparent) 40%, transparent 100%)",
            // Лунный свет: светлый `--ball`, охлаждённый ночным `--cloud`
            "--moonlight": "color-mix(in oklab, var(--color-ball) 72%, var(--color-cloud))",
          } as React.CSSProperties
        }
      />
    </div>
  );
}
