/**
 * Интерьеры домов картинкой — слот под арт владельца (блок 4).
 *
 * Пока файлов нет, комната собирается на CSS 3D (`house-room.tsx`): стены,
 * пол, окно, свет — токенами. Когда владелец сгенерирует интерьер, файл
 * кладётся в `assets-src/room-<id>.png`, `npm run assets` готовит WebP и
 * пишет размеры в манифест — и комната этого дома сама переходит на картинку:
 * фоном идёт интерьер, а контент встаёт на размеченные точки. Правок кода не
 * нужно.
 *
 * Точки — доли картинки (x, y — левый верхний угол, w, h — размер). Они же
 * названы в промпте для генерации: свободные места на стенах интерьера
 * должны лечь ровно сюда. Общие для всех домов, потому что и промпт один —
 * «разрез комнаты, задняя стена фронтально, окно слева».
 *
 * На узком экране и при reduced-motion комната остаётся плоской панелью —
 * картинка интерьера там не показывается: текст важнее эффекта.
 */

import manifest from "@/lib/scene-manifest.json";

export type Spot = { x: number; y: number; w: number; h: number };

export type RoomArt = {
  src: string;
  width: number;
  height: number;
  spots: { sign: Spot; wall: Spot; shelf: Spot; slate: Spot };
};

/** Размеченные места интерьера, доли картинки 2400×1400 (см. промпт в PR). */
export const ROOM_SPOTS: RoomArt["spots"] = {
  // Вывеска — над левой половиной задней стены
  sign: { x: 0.3, y: 0.12, w: 0.34, h: 0.12 },
  // Стена — левая половина задней стены под вывеской
  wall: { x: 0.3, y: 0.26, w: 0.3, h: 0.38 },
  // Полка — правая часть задней стены, пустые доски
  shelf: { x: 0.64, y: 0.14, w: 0.28, h: 0.52 },
  // Планшет — наклонная доска на полу у переднего края
  slate: { x: 0.32, y: 0.7, w: 0.36, h: 0.22 },
};

const FILES: Record<string, { src: string; width: number; height: number }> = manifest;

/** Интерьер дома, если файл уже прошёл конвейер; иначе `null` — CSS-комната. */
export function roomArtFor(stopId: string): RoomArt | null {
  const file = FILES[`room-${stopId}`];
  return file ? { ...file, spots: ROOM_SPOTS } : null;
}
